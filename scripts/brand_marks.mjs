// node scripts/brand_marks.mjs <arrowloop checkout>
// Writes the provider logos of the remotes window from ArrowLoop's marks, which share the sources and licences listed
// in scripts/brand-paths/README.md: frontend/src/features/config/brandMarks.ts with each mark as SVG markup and its
// tile colours, and brandMarks.css with the colours a mark shifts on one of the two grounds.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const al = process.argv[2];
if (!al) throw new Error('usage: node scripts/brand_marks.mjs <arrowloop checkout>');
const out = join(import.meta.dirname, '..', 'frontend', 'src', 'features', 'config');
const tsx = readFileSync(join(al, 'web', 'src', 'components', 'brandGlyphs.tsx'), 'utf8');
const css = readFileSync(join(al, 'web', 'src', 'brandGlyphs.css'), 'utf8');

// React's spelling of the SVG attributes the marks use, and the markup's own.
const ATTRS = {
  fillRule: 'fill-rule', clipRule: 'clip-rule', clipPath: 'clip-path', fillOpacity: 'fill-opacity', strokeWidth: 'stroke-width',
  strokeLinecap: 'stroke-linecap', strokeLinejoin: 'stroke-linejoin', strokeMiterlimit: 'stroke-miterlimit', strokeOpacity: 'stroke-opacity',
  stopColor: 'stop-color', stopOpacity: 'stop-opacity', className: 'class', xlinkHref: 'href', fontFamily: 'font-family', mixBlendMode: 'mix-blend-mode',
};
const kebab = (k) => ATTRS[k] ?? k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

function markup(jsx) {
  return jsx
    .replace(/\s*\{\.\.\.props\}/g, '')
    .replace(/style=\{\{([^}]*)\}\}/g, (_, body) => `style="${[...body.matchAll(/(\w+):\s*"([^"]*)"/g)].map(([, k, v]) => `${kebab(k)}:${v}`).join(';')}"`)
    .replace(/(\s)(\w+)=\{"([^"]*)"\}/g, '$1$2="$3"')
    .replace(/(\s)(\w+)=\{([\d.]+)\}/g, '$1$2="$3"')
    .replace(/(\s)([a-z]+[A-Z]\w*)=/g, (m, sp, k) => (k in ATTRS ? `${sp}${ATTRS[k]}=` : m))
    .replace(/\saria-hidden(?=[\s>])/g, ' aria-hidden="true"')
    .replace(/\n\s*/g, '')
    // A mark with a single colour version for the hover comes as a fragment around both.
    .replace(/^<>(.*)<\/>$/, '$1');
}

const marks = {};
for (const [, name, body] of tsx.matchAll(/export function (Icon\w+)\(props[^)]*\) \{\n\s*return \(\n([\s\S]*?)\n\s*\)\n\}/g)) {
  if (name === 'IconGithub') continue;
  const jsx = markup(body.trim());
  if (/[{}]/.test(jsx.replace(/style="[^"]*"/g, ''))) throw new Error(`${name}: JSX left in ${jsx.slice(0, 120)}`);
  marks[name] = jsx;
}
const tiles = JSON.parse('{' + tsx.match(/BRAND_TILES[^=]*= \{([\s\S]*?)\n\}/)[1].replace(/(\w+): \{ tile: '([^']*)', ink: '([^']*)' \},?/g, '"$1": {"tile":"$2","ink":"$3"},').replace(/,\s*$/, '') + '}');
delete tiles.IconGithub;

writeFileSync(join(out, 'brandMarks.ts'), `// Provider logos for the remotes window, written by scripts/brand_marks.mjs. Each belongs to its owner and stands only on
// the tile that connects to that service, unchanged but for its colour, with no claim of endorsement.
import './brandMarks.css';

export const BRAND_MARKS: Record<string, string> = ${JSON.stringify(marks, null, 2)};

// The colour a tile fills with under the pointer, and the ink its name and mark take there.
export const BRAND_TILES: Record<string, { tile: string; ink: string }> = ${JSON.stringify(tiles, null, 2)};
`);
writeFileSync(join(out, 'brandMarks.css'), css.replace(/GENERATED by scripts\/gen_brand_glyphs\.py, do not hand-edit\./, 'Written by scripts/brand_marks.mjs.').replace(/^\s*--brand-github-0:[^\n]*\n/gm, ''));
console.log(`${Object.keys(marks).length} marks, ${Object.keys(tiles).length} tiles`);
